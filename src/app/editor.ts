// The code behind the shader editor, shared with the visual maker and the assistant: which scene
// is being edited, compiling source into a scene (in the background, the old program keeps
// running), and saving. "My Shader" runs from the start, whether or not the editor has been opened.

import { parseParams } from '../engine/params';
import { COMMON, TEMPLATE, type Scene } from '../engine/scenes';
import { KEYS, readString, writeString } from '../state/persistence';
import { paramKey, saveSceneEdit, saveUserScenes, userScene } from '../state/scene-list';
import type { AppController } from './controller';

const HEADER_LINES = COMMON.split('\n').length - 1;

export type EditorKind = 'custom' | 'builtin' | 'user' | 'nodes';
export interface EditorTarget { index: number; name: string; kind: EditorKind; body: string; original?: string }

// "ERROR: 0:57: 'foo' : undeclared identifier" -> "Line 3: 'foo' : undeclared identifier"
export function formatError(message: string): string {
  return message
    .split('\n')
    .filter((l) => l.startsWith('ERROR'))
    .map((l) => l.replace(/^ERROR: \d+:(\d+): /, (_, n: string) => `Line ${Number(n) - HEADER_LINES}: `))
    .join('\n') || message;
}

export class EditorCore {
  customCode: string;
  nodeCode = '';                       // generated by the visual maker (read-only in the editor)
  libraryName: string | null = null;   // name the code editor's shader will be saved under
  private readonly seq = new Map<number, number>();

  constructor(private readonly app: AppController) {
    this.customCode = readString(KEYS.customShader) ?? TEMPLATE;
    void this.compileInto(this.customTarget(), this.customCode);
  }

  setNodeCode(code: string): void { this.nodeCode = code; }

  customTarget(): EditorTarget {
    return { index: this.app.state.customIndex, name: 'My Shader', kind: 'custom', body: this.customCode };
  }

  kindOf(s: Scene): EditorKind {
    return s.kind === 'custom' ? 'custom' : s.kind === 'nodes' ? 'nodes' : s.user ? 'user' : 'builtin';
  }

  // What the editor shows for scene i: always the scene on screen, edited in place.
  target(i: number): EditorTarget {
    const s = this.app.state.scenes[i]!;
    const kind = this.kindOf(s);
    return { index: i, name: s.name, kind, body: kind === 'nodes' ? this.nodeCode : kind === 'custom' ? this.customCode : s.body, original: s.original };
  }

  // Compiles `source` into the target scene. Resolves with the error text (line numbers relative to
  // `source`), or null once the new program is live and saved. A newer compile for the same scene
  // supersedes an older one that is still in flight.
  async compileInto(target: EditorTarget, source: string): Promise<string | null> {
    const scene = this.app.state.scenes[target.index];
    if (!scene) return 'No such scene.';
    const { code, params } = parseParams(source);
    const frag = COMMON + code;
    const n = (this.seq.get(target.index) ?? 0) + 1;
    this.seq.set(target.index, n);
    const error = await this.app.renderer.compileAsync(frag, scene.name);
    if (error) return formatError(error);
    if (this.seq.get(target.index) !== n) return null;
    scene.frag = frag;
    scene.params = params;
    scene.body = source;
    if (target.kind === 'custom') { this.customCode = source; writeString(KEYS.customShader, source); }
    else if (target.kind === 'builtin') saveSceneEdit(scene, this.app.state.scenes, this.app.parked);
    else if (target.kind === 'user') saveUserScenes(this.app.state.scenes, this.app.parked);
    this.app.setSceneParams(target.index, params);
    this.app.bumpScenes();
    return null;
  }

  // Load code into "My Shader" (Send to code, Edit a copy), whether or not it's the scene on screen.
  setCustomCode(code: string): Promise<string | null> {
    return this.compileInto(this.customTarget(), code);
  }

  // "Save to library": the current editor code as a (new or overwritten) library scene. Returns the
  // index, or undefined when cancelled or not compiling.
  saveToLibrary(body: string, from: EditorTarget): number | undefined {
    const app = this.app;
    const suggestion = { custom: this.libraryName ?? 'My scene', builtin: `${from.name} remix`, user: from.name, nodes: from.name }[from.kind];
    const name = prompt('Name for this scene in the library:', suggestion)?.trim();
    if (!name) return;
    const scenes = app.state.scenes;
    const existing = app.sceneByName(name);
    if (existing >= 0 && !scenes[existing]!.user) { app.toast(`"${name}" is a built-in scene — pick another name.`); return; }
    if (existing >= 0 && !confirm(`Overwrite your scene "${name}"?`)) return;
    if (existing < 0 && app.parked.userScenes.some((p) => p.name === name) && !confirm(`Replace your scene "${name}" (it doesn't compile on this device) with this code?`)) return;
    const scene = userScene(name, body);
    let index = existing;
    if (existing >= 0) {
      const error = app.renderer.replaceScene(existing, scene.frag);
      if (error) { app.toast('Fix the shader errors before saving.'); return; }
      Object.assign(scenes[existing]!, scene);
    } else {
      if (app.renderer.check(scene.frag, name)) { app.toast('Fix the shader errors before saving.'); return; }
      index = scenes.push(scene) - 1;
    }
    if (from.index !== index) app.paramStore.copy(paramKey(scenes[from.index]!), paramKey(scenes[index]!));   // keep the values you tweaked
    app.setSceneParams(index, scene.params);
    this.libraryName = name;
    saveUserScenes(scenes, app.parked);
    app.bumpScenes();
    app.toast(`Saved "${name}" to the library — it's now in the auto-switch rotation`);
    return index;
  }
}
