// The code behind the shader editor, shared with the visual maker and the assistant: which scene
// is being edited, its text, and saving it to the library. Compiling and storing scenes is the scene
// library's (scene-library.ts); the editor keeps "My Shader"'s code, which runs from the start whether
// or not the editor has been opened, and the visual maker's generated code.

import { TEMPLATE, type Scene } from '../scenes';
import type { AppState } from '../state/app-state';
import { KEYS, readString, writeString } from '../state/persistence';
import type { CompileResult, SceneLibrary } from './scene-library';

export type EditorKind = 'custom' | 'builtin' | 'user' | 'nodes';
export interface EditorTarget { index: number; name: string; kind: EditorKind; body: string; original?: string }

export interface EditorDeps {
  readonly state: Pick<AppState, 'scenes' | 'customIndex'>;
  readonly library: SceneLibrary;
  toast(text: string): void;
}

export class EditorCore {
  customCode: string;
  nodeCode = '';                       // generated by the visual maker (read-only in the editor)
  libraryName: string | null = null;   // name the code editor's shader will be saved under

  constructor(private readonly app: EditorDeps) {
    this.customCode = readString(KEYS.customShader) ?? TEMPLATE;
    void this.compileInto(this.customTarget(), this.customCode);
  }

  setNodeCode(code: string): void { this.nodeCode = code; }

  customTarget(): EditorTarget {
    return { index: this.app.state.customIndex, name: 'My Shader', kind: 'custom', body: this.customCode };
  }

  kindOf(s: Scene): EditorKind {
    return s.kind === 'custom' ? 'custom' : s.kind === 'nodes' ? 'nodes' : s.user ? 'user' : 'builtin';
  }

  // What the editor shows for scene i: always the scene on screen, edited in place.
  target(i: number): EditorTarget {
    const s = this.app.state.scenes[i]!;
    const kind = this.kindOf(s);
    return { index: i, name: s.name, kind, body: kind === 'nodes' ? this.nodeCode : kind === 'custom' ? this.customCode : s.body, original: s.original };
  }

  // Compiles `source` into the target scene (SceneLibrary.compile); "My Shader"'s code is kept here.
  async compileInto(target: EditorTarget, source: string): Promise<CompileResult> {
    const result = await this.app.library.compile(target.index, source);
    if (result === null && target.kind === 'custom') { this.customCode = source; writeString(KEYS.customShader, source); }
    return result;
  }

  // Load code into "My Shader" (Send to code, Edit a copy), whether or not it's the scene on screen.
  setCustomCode(code: string): Promise<CompileResult> {
    return this.compileInto(this.customTarget(), code);
  }

  // "Save to library": the current editor code as a (new or overwritten) library scene, keeping the
  // parameter values you tweaked. Returns the index, or undefined when cancelled or not compiling.
  saveToLibrary(body: string, from: EditorTarget): number | undefined {
    const app = this.app;
    const suggestion = { custom: this.libraryName ?? 'My scene', builtin: `${from.name} remix`, user: from.name, nodes: from.name }[from.kind];
    const name = prompt('Name for this scene in the library:', suggestion)?.trim();
    if (!name) return;
    let out = app.library.add(name, body, { valuesFrom: from.index });
    if ('conflict' in out) {
      if (out.conflict === 'builtin') { app.toast(`"${name}" is a built-in scene — pick another name.`); return; }
      const question = out.conflict === 'mine' ? `Overwrite your scene "${name}"?` : `Replace your scene "${name}" (it doesn't compile on this device) with this code?`;
      if (!confirm(question)) return;
      out = app.library.add(name, body, { replace: true, valuesFrom: from.index });
    }
    if ('error' in out) { app.toast('Fix the shader errors before saving.'); return; }
    this.libraryName = name;
    app.toast(`Saved "${name}" to the library — it's now in the auto-switch rotation`);
    return out.index;
  }
}
